#!/usr/bin/env node
/** Build standalone DSH client bundle. --check is read-only. */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const read = (file) => readFileSync(join(root, file), 'utf8')

function closure(file, name, names) {
  const source = read('shared/' + file).replace(/^export\s+(const|function|let)\s/gmu, '$1 ').trim()
  return [
    '    const ' + name + ' = (() => {',
    source.split('\n').map((line) => '      ' + line).join('\n'),
    '      return { ' + names.join(', ') + ' }',
    '    })()',
  ].join('\n')
}

export function build() {
  return [
    '/** GENERATED by miopiik-iui/tools/build.mjs. Do not edit by hand. */',
    'window.__ModuleLoader__.load({',
    "  id: 'miopiik-iui',",
    '  factory(require) {',
    "    const React = require('react')",
    '    const h = React.createElement',
    '    const IUI_PLUGIN_VERSION = ' + JSON.stringify(JSON.parse(read('package.json')).version),
    '    const C = {',
    "      text: 'var(--dsw-alias-label-primary, #ddd)',",
    "      muted: 'var(--dsw-alias-label-secondary, #999)',",
    "      border: 'var(--dsw-alias-border-l1, #555)',",
    "      brand: 'var(--dsw-static-deepseek-500, #4176e6)',",
    "      success: 'var(--dsw-alias-state-success-primary, #2ea043)',",
    "      warn: 'var(--dsw-alias-state-warn-primary, #b08800)',",
    "      idle: 'var(--dsw-alias-state-idle-primary, #999)',",
    "      error: 'var(--dsw-alias-state-error-primary, #d1242f)',",
    '    }',
    closure('iui-ast.js', 'IUI_AST', ['IUI_VERSION', 'REGISTRY', 'LIMITS', 'INLINE_TYPES', 'TONES', 'ICONS', 'readBinding', 'resolveValue', 'validateAst', 'tableMatrix', 'chartMatrix', 'degradeToText']),
    closure('miopiik-ml.js', 'MIOPIIK_ML', ['ML_VERSION', 'ML_TAGS', 'parseMiopiikMl']),
    closure('markdown-segments.js', 'MARKDOWN_SEGMENTS', ['INLINE_TOKEN', 'BLOCK_FENCE', 'splitTrustedMarkdown', 'hasTrustedMarkup']),
    read('renderer.js'),
    read('settings.js'),
    '    return {',
    '      inject: [],',
    '      apply(ctx) {',
    '        const registry = {',
    '          segments: (text) => MARKDOWN_SEGMENTS.splitTrustedMarkdown(text),',
    '          renderInline: (node) => renderInlinePrimitive(node),',
    '          renderBlock: (raw) => {',
    '            const parsed = readIuiFence(raw)',
    '            return parsed.ok ? h(IuiSheet, { sample: parsed.doc, format: parsed.format, degraded: parsed.degraded }) : null',
    '          },',
    '        }',
    '        const previous = globalThis.__miopiikMarkdownEmbeds',
    '        globalThis.__miopiikMarkdownEmbeds = registry',
    '        registerIuiSettings(ctx)',
    '        if (typeof ctx.effect === "function") {',
    '          ctx.effect(() => () => {',
    '            if (globalThis.__miopiikMarkdownEmbeds === registry) {',
    '              if (previous === undefined) delete globalThis.__miopiikMarkdownEmbeds',
    '              else globalThis.__miopiikMarkdownEmbeds = previous',
    '            }',
    '          }, "miopiik-iui: embed registry lifecycle")',
    '        }',
    '      },',
    '    }',
    '  },',
    '})',
    '',
  ].join('\n').replace(/[ \t]+$/gmu, '')
}

const output = join(root, 'client.js')
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== build()) {
    console.error('miopiik-iui/client.js out of sync; run node tools/build.mjs')
    process.exitCode = 1
  } else console.log('standalone IUI client bundle: in sync')
} else {
  writeFileSync(output, build(), 'utf8')
  console.log('wrote', output)
}
